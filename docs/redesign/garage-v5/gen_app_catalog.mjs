// Generates dist/mybil-catalog.js from the v5 catalog and the built asset manifest, so the app only offers
// parts that exist and passed QA. Run after build_layers.py: node docs/redesign/garage-v5/gen_app_catalog.mjs
import fs from 'node:fs';

const cat = JSON.parse(fs.readFileSync('docs/redesign/garage-v5/catalog.json', 'utf8'));
const manifest = JSON.parse(fs.readFileSync('dist/assets/mybil/manifest.json', 'utf8'));
const NAMES = { scooter: ['Scooter', 0], smallcar: ['Lille bil', 25000], bigcar: ['Stor bil', 60000], racecar: ['Racerbil', 120000] };

const slots = Object.entries(cat.slots).map(([id, s]) => ({ id, name: s.name, z: s.z })).sort((a, b) => a.z - b.z);
const parts = cat.parts.map(({ id, slot, name, price, tint, text }) => ({ id, slot, name, price, ...(tint ? { tint } : {}), ...(text ? { text: true } : {}) }));
const bases = Object.keys(NAMES).filter(id => manifest[id]).map(id => ({
  id, name: NAMES[id][0], price: NAMES[id][1],
  parts: manifest[id].parts, split: manifest[id].split, bbox: manifest[id].bbox, plate: manifest[id].plate || null,
}));
const src = `// Generated by docs/redesign/garage-v5/gen_app_catalog.mjs — do not edit by hand.
export const SLOTS = ${JSON.stringify(slots)};
export const PARTS = ${JSON.stringify(parts)};
export const BASES = ${JSON.stringify(bases)};
`;
fs.writeFileSync('dist/mybil-catalog.js', src);
console.log('mybil-catalog.js', bases.map(b => `${b.id}:${b.parts.length}`).join(' '));
