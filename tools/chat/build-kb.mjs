// Builds dist/api/_kb.mjs: the knowledge the chat function searches. Only the app's own, source-checked content.
// Run: node tools/chat/build-kb.mjs   (rerun whenever content.js or lessons.js change; a test checks they match)
import { writeFileSync } from 'node:fs';
import { CHAPTERS, QUESTIONS, SOURCES } from '../../dist/content.js';
import { LESSONS } from '../../dist/lessons.js';

const sections = CHAPTERS.flatMap(ch => ch.sections.map(s => {
  const l = LESSONS[s.id];
  return {
    id: s.id, title: s.title, chapter: ch.title, chapterId: ch.id, facts: s.facts,
    lead: l?.lead || '', cards: (l?.cards || []).map(c => ({ title: c.title, body: c.body })),
    sources: [...new Set([...(s.sourceIds || []), ...((l?.cards || []).flatMap(c => c.sourceIds || []))])],
    ref: s.curriculumRef || ''
  };
}));
const questions = QUESTIONS.map(q => ({ id: q.id, sectionId: q.sectionId, prompt: q.prompt, context: q.context, explanation: q.explanation }));
const sources = Object.fromEntries(SOURCES.map(s => [s.id, { label: s.label, url: s.url, checked: s.checked }]));
const kb = { builtAt: new Date().toISOString().slice(0, 10), sections, questions, sources };
writeFileSync(new URL('../../dist/api/_kb.mjs', import.meta.url), '// Generated by tools/chat/build-kb.mjs — do not edit by hand.\nexport const KB = ' + JSON.stringify(kb) + ';\n');
console.log(`_kb.mjs: ${sections.length} sections, ${questions.length} questions, ${Object.keys(sources).length} sources`);
